#!/usr/bin/env python3
"""Regenerate or verify the self-contained TS1201 Zigbee2MQTT codebook block."""

from __future__ import annotations

import argparse
import base64
import gzip
import hashlib
import io
import json
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BUNDLE_VERSION = "1.4.0"
BEGIN = "// BEGIN TS1201 EMBEDDED CODEBOOK"
END = "// END TS1201 EMBEDDED CODEBOOK"


def embedded_block(raw: bytes, license_text: str) -> str:
    """Preserve the exact source JSON bytes and the complete license notice."""
    source = json.loads(raw)
    if (
        not isinstance(source, dict)
        or source.get("schemaVersion") != 1
        or not isinstance(source.get("brands"), list)
        or not isinstance(source.get("candidates"), list)
    ):
        raise ValueError("Codebook must use schemaVersion 1 with brands and candidates")
    if not license_text.strip() or "*/" in license_text:
        raise ValueError(
            "License must be nonempty and safe to embed in a block comment"
        )
    compressed = io.BytesIO()
    # GzipFile uses a fixed OS byte and omits a filename; no clock or path leaks
    # into the output, including when run under different Python minor versions.
    with gzip.GzipFile(fileobj=compressed, mode="wb", filename="", mtime=0) as stream:
        stream.write(raw)
    encoded = base64.b64encode(compressed.getvalue()).decode("ascii")
    chunks = textwrap.wrap(encoded, width=100)
    data_lines = " +\n".join(f"    '{chunk}'" for chunk in chunks) + ";"
    return (
        f"{BEGIN}\n"
        "// Generated by scripts/embed-ts1201-z2m-codebook.py; do not edit this block.\n"
        f"export const TS1201_BUNDLE_VERSION = '{BUNDLE_VERSION}';\n"
        f"export const TS1201_CODEBOOK_SHA256 = '{hashlib.sha256(raw).hexdigest()}';\n"
        f"export const TS1201_CODEBOOK_BYTES = {len(raw)};\n"
        "/*\n"
        "Embedded codebook license (complete original notice):\n"
        f"{license_text.rstrip()}\n"
        "*/\n"
        "const TS1201_CODEBOOK_GZIP_BASE64 =\n"
        f"{data_lines}\n"
        f"{END}"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify without writing")
    parser.add_argument(
        "--converter", type=Path, default=ROOT / "zemismart_ts1201_ir.mjs"
    )
    parser.add_argument(
        "--codebooks", type=Path, default=ROOT / "data/ts1201-ir-codebooks.json"
    )
    parser.add_argument(
        "--license", type=Path, default=ROOT / "data/ts1201-ir-codebooks-LICENSE.txt"
    )
    args = parser.parse_args()
    try:
        current = args.converter.read_text(encoding="utf-8")
        if current.count(BEGIN) != 1 or current.count(END) != 1:
            raise ValueError(
                "Converter must contain exactly one embedded codebook block"
            )
        start = current.index(BEGIN)
        end = current.index(END) + len(END)
        if end <= start:
            raise ValueError("Embedded codebook block markers are reversed")
        block = embedded_block(
            args.codebooks.read_bytes(), args.license.read_text(encoding="utf-8")
        )
        updated = current[:start] + block + current[end:]
        if updated != current:
            if args.check:
                print(
                    "Embedded codebook is out of date; run this script without --check",
                    file=sys.stderr,
                )
                return 1
            args.converter.write_text(updated, encoding="utf-8")
            print(f"Updated embedded codebook in {args.converter.name}")
        else:
            print("Embedded codebook matches the source JSON and license")
    except (OSError, UnicodeError, ValueError) as error:
        print(f"Cannot build embedded TS1201 codebook: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
